import { Download, FileText, Github, Rocket, Shield } from 'lucide-react';
import type { AnalogueSite } from '@/data/analogueSites';

interface FooterProps {
  sites: AnalogueSite[];
}

function exportJSON(sites: AnalogueSite[]) {
  const data = {
    title: 'TERRAbase: Terrestrial Analogue Explorer',
    challenge: 'NASA Space Apps Challenge',
    exportedAt: new Date().toISOString(),
    sites: sites.map((s) => ({
      earthSite: { name: s.earthName, location: s.earthLocation, coords: s.earthCoords },
      spaceTarget: { name: s.spaceName, location: s.spaceLocation },
      category: s.categoryLabel,
      compatibilityScores: s.metrics,
      thermalDelta: s.thermalDeltaLabel,
      comparisonMetrics: s.comparisonMetrics,
      detailedComparison: s.detailedRows,
    })),
  };
  const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'terrabase-analogue-data.json';
  a.click();
  URL.revokeObjectURL(url);
}

function downloadReport(sites: AnalogueSite[]) {
  const lines: string[] = [];
  lines.push('TERRAbase: Terrestrial Analogue Explorer');
  lines.push('NASA Space Apps Challenge — Submission Report');
  lines.push(`Generated: ${new Date().toLocaleString()}`);
  lines.push('');
  lines.push('='.repeat(60));

  sites.forEach((s) => {
    lines.push('');
    lines.push(`EARTH: ${s.earthName} (${s.earthLocation}) — ${s.earthCoords}`);
    lines.push(`SPACE: ${s.spaceName} (${s.spaceLocation})`);
    lines.push(`Category: ${s.categoryLabel}`);
    lines.push('');
    lines.push('Compatibility Scores:');
    lines.push(`  Topography: ${s.metrics.topography}%`);
    lines.push(`  Soil/Mineral: ${s.metrics.soilMineral}%`);
    lines.push(`  Radiation Shielding: ${s.metrics.radiationShielding}%`);
    lines.push(`  Thermal Delta: ${s.metrics.thermalDelta}% (${s.thermalDeltaLabel})`);
    lines.push('');
    lines.push('Detailed Comparison:');
    s.detailedRows.forEach((r) => {
      lines.push(`  ${r.parameter}:`);
      lines.push(`    Earth: ${r.earthParam}`);
      lines.push(`    Space: ${r.spaceParam}`);
      lines.push(`    Source: ${r.dataSource} (${r.sourceUrl})`);
    });
    lines.push('');
    lines.push('-'.repeat(60));
  });

  lines.push('');
  lines.push('Data Sources: USGS, NASA Earthdata, HiRISE, Copernicus, ESA, JPL');
  lines.push('');
  lines.push('Generated by TERRAbase Analogue Explorer');

  const blob = new Blob([lines.join('\n')], { type: 'text/plain' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'terrabase-nasa-report.txt';
  a.click();
  URL.revokeObjectURL(url);
}

export function Footer({ sites }: FooterProps) {
  return (
    <footer className="relative z-10 mt-12 border-t border-cyan-500/10">
      <div className="mx-auto max-w-7xl px-4 py-8 sm:px-6 lg:px-8">
        <div className="glass-card p-6">
          <div className="flex flex-col gap-6 lg:flex-row lg:items-center lg:justify-between">
            <div className="flex items-center gap-3">
              <div className="flex h-12 w-12 items-center justify-center rounded-xl border border-cyan-500/20 bg-cyan-500/5">
                <Rocket className="h-6 w-6 text-cyan-400" />
              </div>
              <div>
                <h3 className="text-base font-bold text-white">TERRAbase Submission Assets</h3>
                <p className="text-xs text-slate-400">Export data, download the report, or explore the repository.</p>
              </div>
            </div>

            <div className="flex flex-wrap gap-3">
              <button
                onClick={() => exportJSON(sites)}
                className="group flex items-center gap-2 rounded-lg border border-cyan-500/25 bg-cyan-500/10 px-4 py-2.5 text-sm font-semibold text-cyan-300 transition-all duration-200 hover:bg-cyan-500/20 hover:border-cyan-400/40"
              >
                <Download className="h-4 w-4 transition-transform group-hover:translate-y-0.5" />
                Export Data (JSON)
              </button>

              <button
                onClick={() => downloadReport(sites)}
                className="group flex items-center gap-2 rounded-lg border border-emerald-500/25 bg-emerald-500/10 px-4 py-2.5 text-sm font-semibold text-emerald-300 transition-all duration-200 hover:bg-emerald-500/20 hover:border-emerald-400/40"
              >
                <FileText className="h-4 w-4" />
                Download NASA Report
              </button>

              <a
                href="https://github.com"
                target="_blank"
                rel="noopener noreferrer"
                className="group flex items-center gap-2 rounded-lg border border-slate-500/25 bg-slate-700/20 px-4 py-2.5 text-sm font-semibold text-slate-300 transition-all duration-200 hover:bg-slate-700/40 hover:border-slate-400/40"
              >
                <Github className="h-4 w-4" />
                View GitHub Repository
              </a>
            </div>
          </div>

          <div className="mt-6 flex flex-col items-center justify-between gap-3 border-t border-cyan-500/10 pt-4 sm:flex-row">
            <p className="text-xs text-slate-500">
              TERRAbase Analogue Explorer — NASA Space Apps Challenge
            </p>
            <div className="flex items-center gap-1.5 text-xs text-slate-500">
              <Shield className="h-3 w-3 text-cyan-500/50" />
              Data: USGS, NASA Earthdata, HiRISE, Copernicus, ESA
            </div>
          </div>
        </div>
      </div>
    </footer>
  );
}
